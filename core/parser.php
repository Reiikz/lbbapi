function bind9_zonedb_encode($dbarray){
    $out = ";       Zone Database Generated by Light Bind9 Basic API\n";
    $out .= "\n\n;------------------------------- DB CFG\n";
    //Default TTL
    $out .= "\$TTL      " . $dbarray["DEFAULT_TTL"] . "\n";

    if(!str_ends_with($dbarray["SOA"], ".")){
        $dbarray["SOA"] = $dbarray["SOA"] . ".";
    }
    //Generate SOA
    $out .= "@      IN      SOA     " . $dbarray["SOA"] . "      " . $dbarray["SOA_SERVER"] . " (\n";
    $out .= "                       " . $dbarray["SERIAL"] . "      ; SERIAL\n";
    $out .= "                       " . $dbarray["REFRESH"] . "      ; REFRESH\n";
    $out .= "                       " . $dbarray["RETRY"] . "      ; RETRY\n";
    $out .= "                       " . $dbarray["EXPIRE"] . "      ; EXPIRE\n";
    $out .= "                       " . $dbarray["NEGATIVE_CACHE_TTL"] . " )     ; NEGATIVE_CACHE_TTL\n";
    
    $out .= "\n\n;------------------------------- RECORDSET\n\n\n";

    $default_ttl = $dbarray["DEFAULT_TTL"];

    $blankSpaces=0;
    foreach($dbarray["recordset"] as $dbarraykey => $record){
        $len = strlen($dbarraykey);
        if($len >  $blankSpaces){
            $blankSpaces = $len;
        }
    }
    $blankSpacesCount = $blankSpaces;
    $blankSpaces = "";

    foreach($dbarray["recordset"] as $dbarrykey => $record){
        $out .= ";----------- " . "$dbarrykey\n";
        foreach($record["types"] as $recordType){
            foreach($record[$recordType] as $entry){
                $ttl = $entry["ttl"];
                if($ttl == $default_ttl){
                    $ttl = "";
                }

                $recName = $dbarrykey;
                if($recName == $dbarray["SOA"]){
                    $recName = "@";
                }

                //calculate blank spaces for the record so they lign up neatly
                $curSpaces = $blankSpacesCount - strlen($recName) + 4;
                $blankSpaces = "";
                for($x = 0; $x < $curSpaces; $x++) {
                    $blankSpaces .= " ";
                }

                //calculate blank spaces for the record type so they lign up neatly
                $curSpaces = 10 - strlen($recordType) + 4;
                $recordBlankSpaces = "";
                for($x = 0; $x < $curSpaces; $x++) {
                    $recordBlankSpaces .= " ";
                }

                //calculate blank spaces for the record ttl so they lign up neatly
                $curSpaces = 10 - strlen($ttl) + 4;
                $recordTTLBlankSpaces = "";
                for($x = 0; $x < $curSpaces; $x++) {
                    $recordTTLBlankSpaces .= " ";
                }

                

                $out .= "$recName$blankSpaces $ttl$recordTTLBlankSpaces" . "IN      $recordType$recordBlankSpaces" . $entry["value"] . "\n";
            }
        }
        $out .= "\n\n";
    }

    if(strlen($out) < 3){
        return null;
    }else{
        return $out;
    }
}

function bind9_zonedb_generate_default($zone, $server){
    if(empty($zone)){
        header("HTTP/1.1 400 Bad request!");
        echo "<h1>DNS zone cannot be an empty string bind9_zonedb_generate()</h1>";
        exit(0);
        return;
    }
    $SOA = $zone;
    if(!preg_match("/\.{1}$/", $zone)){
        $SOA = "$SOA.";
    }
    if(!str_ends_with($server, ".")){
        $server .= ".";
    }
    return array(
        "DEFAULT_TTL" => 60,
        "SOA" => $SOA,
        "SOA_SERVER" => $server,
        "SERIAL" => 0,
        "REFRESH" => 3600,
        "RETRY" => 31536000,
        "EXPIRE" => 604800,
        "NEGATIVE_CACHE_TTL" => 300,
        "recordset" => array(),
    );
}